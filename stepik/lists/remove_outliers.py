# На вход программе подаются натуральное число n, затем n различных натуральных чисел.
# Написать программу, которая удаляет наименьшее и наибольшее значение из указанных чисел, а затем
# выводит оставшиеся числа каждое на отдельной строке, не меняя их порядок.

n = int(input())
x = []
for _ in range(n):
    x.append(int(input()))

smallest = min(x)
largest = max(x)

x.remove(smallest)
x.remove(largest)

print(*x, sep='\n')