# Условие: на вход подаётся натуральное число n (n >= 2), затем n целых чисел.
# Создать из этих чисел список, состоящий из сумм соседних чисел
# (первое + второе, второе + третье и т.д.), и вывести его.


n = int(input())
result = [] # итоговый список
x = int(input())

for _ in range(n - 1):
    y = int(input())
    z = x + y
    result.append(z)
    x = y
    
print(result)