# На вход программе подаются число n, а затем - n песен из плейлиста Сэма, каждая на отдельной строке. 
# Написать программу, которая сортирует эти песни в алфавитном порядке и выводит каждую из них на отдельной строке.

n = int(input())
s = list()

for _ in range(n):
    x = input()
    s.append(x)
    
s.sort()    
print(*s, sep='\n')


