# На вход программе подаётся строка текста, содержащая 4 целых неотрицательных числа, разделённых точкой.
# Написать программу, которая определяет, является ли введённая строка текста корректным ip-адресом.

s = input().split('.')
if 0 <= int(s[0]) <= 255 and 0 <= int(s[1]) <= 255 and 0 <= int(s[2]) <= 255 and 0 <= int(s[3]) <= 255:
    print('ДА')
else:
    print('НЕТ')



