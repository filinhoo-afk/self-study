# На вход программе подаётся строка, содержащая английский текст. 
# Написать программу, которая подсчитывает общее количество артиклей a, an, the и выводит текст в следующем формате:
# Общее количество артиклей: <total>

s = input().split()
cnt = s.count('a') + s.count('A') + s.count('an') + s.count('An') + s.count('the') + s.count('The')
print(f'Общее количество артиклей: {cnt}')



