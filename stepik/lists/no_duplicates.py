# На вход программе подаются натуральное число n, затем n строк.
# Написать программу, которая выводит только уникальные строки, в том же порядке, в котором они были введены.


n = int(input())
s = []

for _ in range(n):
    line = input()
    if line not in s:
        s.append(line)
print(*s, sep='\n')