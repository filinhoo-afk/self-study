# Задача: написать функцию print_digit_sum(num), которая считает сумму цифр
# целого числа num и печатает её. Например, для 12345 результат 15.

# объявление функции
def print_digit_sum(num):
    sum_num = 0              # сюда будем складывать цифры
    while num > 0:
        sum_num += num % 10  # берём последнюю цифру числа
        num = num // 10      # отбрасываем последнюю цифру
    print(sum_num)

# считываем данные
n = int(input())

# вызываем функцию
print_digit_sum(n)