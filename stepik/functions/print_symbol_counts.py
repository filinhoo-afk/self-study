# Задача: написать функцию print_symbol_counts(s), которая для каждой буквы слова s
# (в нижнем регистре, в алфавитном порядке) печатает, сколько раз она встречается.
# Формат строки: "<буква>: <количество>". Заглавные и строчные считаются одной буквой.

# объявление функции
def print_symbol_counts(s):
    s = s.lower()                 # приводим всё к нижнему регистру
    letters = sorted(set(s))      # уникальные буквы по алфавиту

    for letter in letters:
        count = s.count(letter)   # сколько раз буква встречается в слове
        print(letter + ': ' + str(count))

# считываем данные
s = input()

# вызываем функцию
print_symbol_counts(s)