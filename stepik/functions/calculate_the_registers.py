# Задача: написать функцию print_case_counts(s), которая считает в строке s
# буквы в верхнем и нижнем регистре (небуквенные символы игнорируются)
# и печатает два результата:
# "Букв в верхнем регистре: <U>" и "Букв в нижнем регистре: <L>".

# объявление функции
def print_case_counts(s):
    up = 0      # счётчик заглавных букв
    low = 0     # счётчик строчных букв
    for symbol in s:
        if symbol.isupper():
            up += 1
        elif symbol.islower():
            low += 1
        # цифры, "_", "!" и другие символы не подходят ни под одно условие,
        # поэтому они просто пропускаются
    print('Букв в верхнем регистре:', up)
    print('Букв в нижнем регистре:', low)

# считываем данные
s = input()

# вызываем функцию
print_case_counts(s)