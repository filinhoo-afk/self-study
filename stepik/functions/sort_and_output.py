# Задача: написать функцию print_sorted_hyphen(s), которая принимает строку
# из слов, разделённых дефисами, и печатает эти слова в алфавитном
# (лексикографическом) порядке, также через дефис.

# объявление функции
def print_sorted_hyphen(s):
    words = s.split('-')        # режем строку на слова по дефису
    words.sort()                # сортируем слова по алфавиту
    result = '-'.join(words)    # склеиваем обратно через дефис
    print(result)

# считываем данные
s = input()

# вызываем функцию
print_sorted_hyphen(s)