# На вход программе подаётся строка генетического кода, состоящая из букв А, Г, Ц, Т
# Написать программу, которая подсчитывает сколько аденина, гуанина, цитозина и тимина входит в данную строку генетического кода.

s = input().lower()

print('Аденин:',s.count('а'))
print('Гуанин:',s.count('г'))
print('Цитозин:',s.count('ц'))
print('Тимин:',s.count('т'))



