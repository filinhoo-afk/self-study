# В первой строке подаётся сдвиг n (1 <= n <= 25),
# во второй - закодированное сообщение из строчных латинских букв.
# Декодировать сообщение (сдвинуть каждую букву назад на n по алфавиту)
# и вывести результат одной строкой.

n = int(input())
s = input()
res = ''
for c in s:
    res += chr((ord(c) - 97 - n) % 26 + 97)
print(res)