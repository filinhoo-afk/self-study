# Символы в диапазоне
# На вход подаются два натуральных числа a и b (a < b), каждое на отдельной строке.
# Для каждого кодового значения от a до b (включительно) вывести
# соответствующий ему символ из таблицы Unicode.

a = int(input())
b = int(input())
for i in range(a, b + 1):
    print(chr(i), end=' ')