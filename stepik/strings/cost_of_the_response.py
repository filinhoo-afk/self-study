# Стоимость ответа
# За каждый символ сообщения Сэму платят: <код символа Unicode> * 3 пчёлок-coin.
# Стоимость сообщения - сумма стоимостей всех символов.
# На вход подаётся строка текста (ответ Сэма).
# Вывести в формате:
# Текст сообщения: '<текст сообщения Сэма>'
# Стоимость сообщения: <стоимость>🐝

s = input()
cost = sum(ord(c) * 3 for c in s)
print(f"Текст сообщения: '{s}'")
print(f"Стоимость сообщения: {cost}🐝")