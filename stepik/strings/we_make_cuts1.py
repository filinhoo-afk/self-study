# На вход программе подаётся одна строка. Напишите программу, которая выводит:
# 1. общее количество символов в строке; 2. исходную строку, повторённую 3 раза; 3. первый символ строки;
# 4. первые три символа строки; 5. последние три символа строки; 6. строку в обратном порядке; 7. строку с удалённым первым и последним символами.


s = input()
print(len(s), s * 3, s[0], s[0:3], s[-3:], s[::-1], s[1:-1], sep='\n')