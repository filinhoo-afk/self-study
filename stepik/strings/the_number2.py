# На вход программе подаётся одна строка. Написать программу, которая выводит сообщение «Цифра» (без кавычек), если строка содержит цифру.
# В противном случае вывести сообщение «Цифр нет» (без кавычек).

n = input()
a = 'Цифр нет'

for i in range(len(n)):
    if n[i] in '0123456789':
        a = 'Цифра'
        break
print(a)
