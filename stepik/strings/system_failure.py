# Сбой в системе
# Все буквы русского алфавита в тексте отображаются как [u-<номер символа в Unicode>].
# На вход подаётся строка текста.
# Заменить все такие конструкции на соответствующие буквы и вывести строку.

s = input()
for i in range(1040, 1104):  # коды русских букв А-Я и а-я
    s = s.replace(f'[u-{i}]', chr(i))
    s = s.replace(f'[υ-{i}]', chr(i))  # вариант с греческой υ
print(s)