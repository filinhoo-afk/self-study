# На вход программе подаётся одна строка. Написать программу, которая определяет, сколько раз в строке встречаются символы + и *, и выводит текст в следующем формате: 
# Символ + встречается <n> раз 
# Символ * встречается <m> раз

n = input()
symbol = 0
symbolplus = 0

for i in range(len(n)):
    if n[i] in '+':
        symbolplus += 1
    if n[i] in '*':
        symbol += 1
print('Символ + встречается', symbolplus, 'раз')
print('Символ * встречается', symbol, 'раз')

