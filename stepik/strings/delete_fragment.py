# На вход программе подаётся строка текста, в которой буква «h» встречается минимум два раза. 
# Написать программу, которая удаляет из этой строки первое и последнее вхождение буквы «h», а также все символы, находящиеся между ними.

s = input()

first = s.find('h')
last = s.rfind('h')  

print(s[:first] + s[last + 1:])



