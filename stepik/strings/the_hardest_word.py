# Самое тяжёлое слово
# Тяжесть слова - сумма кодов Unicode всех его символов.
# На вход подаются 4 слова, каждое на отдельной строке.
# Вывести самое тяжёлое слово (если таких несколько, вывести первое из них).

best = ''
best_w = -1
for _ in range(4):
    w = input()
    s = sum(ord(c) for c in w)
    if s > best_w:
        best_w = s
        best = w
print(best)