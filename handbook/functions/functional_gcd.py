# Написать функцию gcd, которая принимает два натуральных числа
# и возвращает их наибольший общий делитель (НОД).
# В решении должны быть только функции, без вызовов требуемых функций.

def gcd(a, b):
    while a != b:
        if a > b:
            a = a - b
        else:
            b = b - a
    return a
