# Напишите функцию take_small(money), которая принимает список номиналов
# и возвращает новый список только с теми значениями, которые меньше 100.
# Порядок элементов должен сохраниться, исходный список менять нельзя.
# В решении не должно быть вызовов требуемых функций.

def take_small(money):
    y = []
    for x in money:
        if x < 100:
            y.append(x)
    return y